"""Tests for raw G-code header metadata used by the File Manager."""

from backend.app.api.routes.library import extract_gcode_file_metadata, extract_gcode_metadata


def test_extracts_elegoo_initial_filament_after_startup_commands():
    metadata = extract_gcode_metadata(
        "; EXECUTABLE_BLOCK_START\n"
        "EXECUTABLE_OBJECT_DEFINE NAME=Kuma_Front_Flat.stp\n"
        "M73 P0 R335\n"
        "M106 S0\n"
        "; print date: 20240520\n"
        "; printer_model:Elegoo Centauri Carbon\n"
        ";initial_filament:PETG\n"
        ";LAYER:0\n"
    )

    assert metadata == {"filament_type": "PETG"}


def test_extracts_orca_filament_type_from_header():
    metadata = extract_gcode_metadata("; generated by OrcaSlicer\n; filament_type = PETG\nG28\n")

    assert metadata == {"filament_type": "PETG"}


def test_normalizes_multimaterial_header_into_distinct_types():
    metadata = extract_gcode_metadata("; filament_type = PLA;PETG;PLA\nG28\n")

    assert metadata == {"filament_type": "PLA, PETG"}


def test_ignores_filament_markers_after_first_layer():
    metadata = extract_gcode_metadata("; filament_type = PETG\n;LAYER:0\n; initial_filament: ABS\n")

    assert metadata == {"filament_type": "PETG"}


def test_extract_gcode_file_metadata_orca_snapmaker(tmp_path):
    gcode_content = (
        "; generated by Snapmaker Orca 2.4.0\n"
        "; total layer number: 181\n"
        "EXCLUDE_OBJECT_DEFINE NAME=Part1\n"
        ";LAYER:0\n"
        "G1 X10 Y10 E1\n"
        "; EXECUTABLE_BLOCK_END\n"
        "; filament used [g] = 0.00, 0.00, 25.79, 0.00, 0.00\n"
        "; filament used [mm] = 0.00, 0.00, 8578.68, 0.00, 0.00\n"
        "; estimated printing time (normal mode) = 2h 27m 46s\n"
        "; curr_bed_type = Textured PEI Plate\n"
        "; extruder_colour = #000000;#21FF06;#B39B84;#B3B3B3;#F73CA0\n"
        "; filament_colour = #000000;#21FF06;#B39B84;#B3B3B3;#F73CA0\n"
        "; filament_type = PETG;PETG;PETG;PETG;TPU\n"
        "; printer_model = Snapmaker U1\n"
        "; layer_height = 0.2\n"
        "; nozzle_diameter = 0.4,0.4,0.4,0.4\n"
    )
    p = tmp_path / "test.gcode"
    p.write_text(gcode_content)

    meta = extract_gcode_file_metadata(p)
    assert meta["print_time_seconds"] == 8866
    assert meta["bed_type"] == "Textured PEI Plate"
    assert meta["layer_height"] == 0.2
    assert meta["total_layers"] == 181
    assert meta["filament_used_grams"] == 25.8
    assert meta["filament_type"] == "PETG"
    assert meta["filament_color"] == "#B39B84"
    assert meta["sliced_for_model"] == "Snapmaker U1"
    assert meta["printable_objects"] == {1: "Part1"}
    assert len(meta["filaments"]) == 1
    assert meta["filaments"][0] == {
        "slot_id": 3,
        "type": "PETG",
        "color": "#B39B84",
        "used_grams": 25.8,
        "used_meters": 8.58,
        "used_in_plate": True,
    }


def test_extract_gcode_file_metadata_with_polygons(tmp_path):
    gcode_content = (
        "; generated by OrcaSlicer 2.0.0\n"
        "EXCLUDE_OBJECT_DEFINE NAME=Screw_Cap CENTER=120.5,85.0 POLYGON=[[110.0,75.0],[131.0,75.0],[131.0,95.0],[110.0,95.0]]\n"
        "EXCLUDE_OBJECT_DEFINE NAME=Nut_Plug CENTER=45.0,50.0 POLYGON=[[40.0,45.0],[50.0,45.0],[50.0,55.0],[40.0,55.0]]\n"
        "; bed_shape = 0x0,250x0,250x250,0x250\n"
        "; curr_bed_type = Textured PEI Plate\n"
    )
    p = tmp_path / "test_polys.gcode"
    p.write_text(gcode_content)

    meta = extract_gcode_file_metadata(p)
    assert meta["bed_size"] == [250.0, 250.0]
    assert 1 in meta["printable_objects"]
    assert meta["printable_objects"][1]["name"] == "Screw_Cap"
    assert meta["printable_objects"][1]["center"] == [120.5, 85.0]
    assert meta["printable_objects"][1]["polygon"] == [[110.0, 75.0], [131.0, 75.0], [131.0, 95.0], [110.0, 95.0]]
    assert 2 in meta["printable_objects"]
    assert meta["printable_objects"][2]["name"] == "Nut_Plug"

